type Dict = (typeof dict)[Lang];

type Ctx = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: Dict;
};

const I18nContext = createContext<Ctx | null>(null);

function detect(): Lang {
  if (typeof window === "undefined") return "pt";
  const stored = window.localStorage.getItem("silentcut.lang");
  if (stored === "pt" || stored === "en") return stored;
  return navigator.language?.toLowerCase().startsWith("pt") ? "pt" : "en";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("pt");
  const hydratedFromServer = useRef(false);

  useEffect(() => {
    setLangState(detect());
    if (typeof window === "undefined") return;
    const onStorage = (e: StorageEvent) => {
      if (e.key !== "silentcut.lang") return;
      if (e.newValue === "pt" || e.newValue === "en") setLangState(e.newValue);
    };
    const onCustom = (e: Event) => {
      const detail = (e as CustomEvent<Lang>).detail;
      if (detail === "pt" || detail === "en") setLangState(detail);
    };
    window.addEventListener("storage", onStorage);
    window.addEventListener("silyc:lang-changed", onCustom as EventListener);
    return () => {
      window.removeEventListener("storage", onStorage);
      window.removeEventListener("silyc:lang-changed", onCustom as EventListener);
    };
  }, []);

  // When a session exists, prefer the server-stored preference and keep it in sync.
  useEffect(() => {
    let cancelled = false;
    async function loadFromServer() {
      try {
        const { data } = await supabase.auth.getSession();
        if (!data.session) return;
        const prefs = await getMyProfile();
        if (cancelled) return;
        hydratedFromServer.current = true;
        if (prefs.preferredLanguage && prefs.preferredLanguage !== lang) {
          setLangState(prefs.preferredLanguage);
          if (typeof window !== "undefined") {
            window.localStorage.setItem("silentcut.lang", prefs.preferredLanguage);
          }
        }
      } catch {
        // Non-fatal: fall back to local detection.
      }
    }
    loadFromServer();
    const { data: sub } = supabase.auth.onAuthStateChange((event) => {
      if (event === "SIGNED_IN") loadFromServer();
      if (event === "SIGNED_OUT") hydratedFromServer.current = false;
    });
    return () => {
      cancelled = true;
      sub.subscription.unsubscribe();
    };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  const setLang = (l: Lang) => {
    setLangState(l);
    if (typeof window !== "undefined") {
      window.localStorage.setItem("silentcut.lang", l);
      window.dispatchEvent(new CustomEvent<Lang>("silyc:lang-changed", { detail: l }));
    }
    // Best-effort persist for signed-in users; ignore errors (offline / not auth'd).
    void (async () => {
      try {
        const { data } = await supabase.auth.getSession();
        if (!data.session) return;
        await updateMyLanguage({ data: { language: l } });
      } catch {
        /* ignore */
      }
    })();
  };
  const value = useMemo<Ctx>(() => ({ lang, setLang, t: dict[lang] as Dict }), [lang]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used within I18nProvider");
  return ctx;
}